"""Independent S4 linear state-estimation pilot with causal delayed replay.

Each packet has capture and delivery ticks. Values are generated by the local
plant at capture; only delivered packets enter the estimator. Oracle model
parameters are privileged theory references, never learned-model features.
"""
from __future__ import annotations

from dataclasses import dataclass
import math

import numpy as np


REGIMES = ("nominal", "q_up", "r_up", "ab_switch")
DELAYS = (0, 2, 4)
FEATURES = (
    "observed_position", "present", "fresh", "age_seconds", "dt_seconds",
    "previous_applied_action", "quality", "quality_present",
)
_H = np.array([1.0, 0.0])


@dataclass(frozen=True)
class Config:
    dt: float = .02
    horizon: int = 500
    change_tick: int = 200
    acquisition_every: int = 1
    delay_jitter_max: int = 0
    process_position_sd: float = .008
    process_velocity_sd: float = .024
    measurement_sd: float = .035
    q_add_position_sd: float = .070
    q_add_velocity_sd: float = .070
    switched_actuator_gain: float = .65
    switched_velocity_decay: float = .975
    quality_signal: float = 1.0
    quality_noise_sd: float = .65
    max_abs_action: float = 4.0
    kp: float = 4.0
    kd: float = 2.8
    adaptive_forgetting: float = .98
    adaptive_temperature: float = 1.0

    def __post_init__(self):
        if not (type(self.horizon) is int and 2 <= self.horizon
                and type(self.change_tick) is int and 1 <= self.change_tick < self.horizon
                and type(self.acquisition_every) is int and self.acquisition_every >= 1
                and type(self.delay_jitter_max) is int and self.delay_jitter_max >= 0
                and math.isfinite(self.dt) and self.dt > 0):
            raise ValueError("Invalid causal timeline")
        if self.change_tick % self.acquisition_every != 0:
            raise ValueError("An acquisition is required exactly at the declared covariance switch")
        if not all(math.isfinite(v) and v > 0 for v in (
            self.process_position_sd, self.process_velocity_sd, self.measurement_sd,
            self.q_add_position_sd, self.q_add_velocity_sd, self.switched_actuator_gain,
            self.switched_velocity_decay, self.quality_noise_sd, self.max_abs_action,
            self.kp, self.kd, self.adaptive_temperature,
        )) or not 0 < self.adaptive_forgetting < 1 or not math.isfinite(self.quality_signal):
            raise ValueError("Invalid process/noise/controller settings")


@dataclass(frozen=True)
class Scenario:
    regime: str
    delay: int
    seed: int
    quality_available: bool = False

    def __post_init__(self):
        if (self.regime not in REGIMES or type(self.delay) is not int or self.delay not in DELAYS
                or type(self.seed) is not int or self.seed < 0 or type(self.quality_available) is not bool):
            raise ValueError("Unregistered scenario identity")


@dataclass(frozen=True)
class Packet:
    source_tick: int
    arrival_tick: int
    value: float
    quality: float = 0.
    quality_present: bool = False


@dataclass(frozen=True)
class Tape:
    scenario: Scenario
    cfg: Config
    packets: tuple[Packet, ...]
    truth: np.ndarray
    action: np.ndarray
    process_increments: np.ndarray
    measurement_increments: np.ndarray
    reference: np.ndarray
    f: np.ndarray
    b: np.ndarray
    q: np.ndarray
    r: np.ndarray


def dynamics(cfg, regime="nominal"):
    """Return one regime's F, B, Q and scalar R (position observation)."""
    if regime not in REGIMES:
        raise ValueError(regime)
    dt = cfg.dt
    f = np.array([[1., dt], [0., 1.]])
    b = np.array([dt**2 / 2., dt])
    q = np.diag([cfg.process_position_sd**2, cfg.process_velocity_sd**2])
    r = cfg.measurement_sd**2
    if regime == "q_up":
        q += np.diag([cfg.q_add_position_sd**2, cfg.q_add_velocity_sd**2])
    elif regime == "r_up":
        # Match the one-step predicted innovation variance at the exact onset.
        r += cfg.q_add_position_sd**2
    elif regime == "ab_switch":
        f[1, 1] = cfg.switched_velocity_decay
        b *= cfg.switched_actuator_gain
    return f, b, q, float(r)


def _freeze(*arrays):
    for a in arrays:
        a.setflags(write=False)


def generate_tape(cfg, regime, delay, seed, quality_available=False):
    """Generate paired exogenous noise, reference and packet timing.

    Initial state/reference/actions and standard-normal streams are identical
    across regimes for one seed. Capture/arrival do not depend on plant state.
    Tape packet values describe the fixed-action replay; true closed loops
    replace them with same-time observations of their own new plant.
    """
    scenario = Scenario(regime, delay, int(seed), quality_available)
    rg = [np.random.default_rng(x) for x in np.random.SeedSequence(seed).spawn(6)]
    t = np.arange(cfg.horizon) * cfg.dt
    phase, phase2 = rg[0].uniform(-np.pi, np.pi, size=2)
    ref = np.column_stack((.7 * np.sin(.85*t + phase), .7*.85*np.cos(.85*t + phase)))
    action = np.clip(.85 * np.sin(1.5*t + phase2) + .35 * np.cos(.60*t + phase),
                     -cfg.max_abs_action, cfg.max_abs_action)
    f0, b0, q0, r0 = dynamics(cfg)
    f1, b1, q1, r1 = dynamics(cfg, regime)
    f = np.repeat(f0[None], cfg.horizon, axis=0); f[cfg.change_tick:] = f1
    b = np.repeat(b0[None], cfg.horizon, axis=0); b[cfg.change_tick:] = b1
    q = np.repeat(q0[None], cfg.horizon, axis=0); q[cfg.change_tick:] = q1
    r = np.full(cfg.horizon, r0); r[cfg.change_tick:] = r1
    process = rg[1].normal(size=(cfg.horizon, 2)) * np.sqrt(np.diagonal(q, axis1=1, axis2=2))
    process[0] = 0.
    measurement = rg[2].normal(size=cfg.horizon) * np.sqrt(r)
    truth = np.zeros((cfg.horizon, 2)); truth[0] = rg[3].normal(0, [.12, .15])
    for k in range(1, cfg.horizon):
        truth[k] = f[k] @ truth[k-1] + b[k] * action[k-1] + process[k]
    capture = range(0, cfg.horizon, cfg.acquisition_every)
    jitter = rg[4].integers(0, cfg.delay_jitter_max + 1, cfg.horizon)
    quality = rg[5].normal(0, cfg.quality_noise_sd, cfg.horizon)
    if regime == "r_up":
        quality[cfg.change_tick:] -= cfg.quality_signal
    packets = tuple(Packet(k, k + delay + int(jitter[k]), float(truth[k, 0] + measurement[k]),
                           float(quality[k]) if quality_available else 0., quality_available)
                    for k in capture)
    _freeze(truth, action, process, measurement, ref, f, b, q, r)
    return Tape(scenario, cfg, packets, truth, action, process, measurement, ref, f, b, q, r)


class DelayedKalman:
    """Known-model, capture-aligned Gaussian update with causal forward replay."""

    def __init__(self, cfg, *, constant=None, tape=None):
        self.cfg = cfg
        self.constant = dynamics(cfg) if constant is None else constant
        self.tape = tape
        self.mean = np.zeros((cfg.horizon, 2))
        self.cov = np.zeros((cfg.horizon, 2, 2))
        self.actions = np.zeros(cfg.horizon)
        self.accepted = {}
        self.tick = -1
        self.initial_cov = np.diag([.12**2, .15**2])

    def _params(self, tick):
        if self.tape is None:
            return self.constant
        return self.tape.f[tick], self.tape.b[tick], self.tape.q[tick], self.tape.r[tick]

    def step(self, tick, previous_action, delivered):
        if tick != self.tick + 1:
            raise ValueError("Estimator requires one call per consecutive control tick")
        self.tick = tick
        self.actions[tick] = previous_action
        new = {}
        for packet in delivered:
            source = packet.source_tick
            if not 0 <= source <= packet.arrival_tick == tick or source in self.accepted or source in new:
                raise ValueError("Duplicate or noncausal packet delivery")
            new[source] = packet
        first = min(new, default=tick)
        self.accepted.update(new)
        scores = {}
        for k in range(first, tick + 1):
            f, b, q, r = self._params(k)
            if k > 0:
                prior = f @ self.mean[k-1] + b * self.actions[k]
                p = f @ self.cov[k-1] @ f.T + q
            else:
                prior, p = np.zeros(2), self.initial_cov.copy()
            if k in self.accepted:
                packet = self.accepted[k]
                innovation = packet.value - prior[0]
                variance = p[0,0] + r
                gain = p[:,0] / variance
                if k in new:
                    scores[k] = (float(innovation), float(variance), float(gain[0]))
                prior = prior + gain * innovation
                j = np.eye(2) - np.outer(gain, _H)
                p = j @ p @ j.T + r * np.outer(gain, gain)
            self.mean[k], self.cov[k] = prior, p
        return self.mean[tick].copy(), scores


class AdaptiveKF:
    """Deployable change-blind discounted mixture of delayed KF hypotheses.

    Hypothesis families and forgetting are set prospectively. The filter
    never sees the true regime, onset, state or generating covariance.
    Capture-aligned Gaussian likelihood scores are exact in source order;
    for reordered samples the per-event score is a causal approximation,
    not a claim of exact optimal Bayesian mode inference.
    """

    def __init__(self, cfg):
        self.cfg = cfg
        self.filters = [DelayedKalman(cfg, constant=dynamics(cfg, name)) for name in REGIMES]
        self.log_weight = np.zeros(len(self.filters))
        self.weights = np.full(len(self.filters), 1 / len(self.filters))

    def step(self, tick, previous_action, delivered):
        states, records = zip(*(f.step(tick, previous_action, delivered) for f in self.filters), strict=True)
        if delivered:
            log_score = []
            for hypotheses in records:
                log_score.append(-.5 * sum(math.log(v) + e*e/v for e, v, _ in hypotheses.values()))
            self.log_weight = self.cfg.adaptive_forgetting * self.log_weight + np.asarray(log_score) / self.cfg.adaptive_temperature
            self.log_weight -= self.log_weight.max()
            weight = np.exp(self.log_weight)
            self.weights = weight / weight.sum()
        return self.weights @ np.stack(states), records[0]


def rollout(cfg, tape, method="fixed_kf", residual=None, closed_loop=False,
            perturb_source_tick=None, perturb_delta=0.):
    """Return arrays and paired causal event logs; no file I/O.

    Residual receives raw[8] and causal KF estimate[2] and returns a correction.
    Holding `closed_loop=False` keeps actions exogenous and makes finite
    differences of past observations intrinsic to the observer.
    """
    if tape.cfg != cfg or method not in ("fixed_kf", "oracle_kf", "adaptive_kf"):
        raise ValueError("Unknown observer or mismatched configuration")
    if residual is not None and method == "oracle_kf":
        raise ValueError("Do not feed privileged oracle estimates to a learned residual")
    if not math.isfinite(perturb_delta) or (perturb_source_tick is not None and
            perturb_source_tick not in {p.source_tick for p in tape.packets}):
        raise ValueError("Impulse must target one actual acquisition")
    if method == "adaptive_kf":
        observer = AdaptiveKF(cfg)
    else:
        observer = DelayedKalman(cfg, tape=tape if method == "oracle_kf" else None)
    horizon = cfg.horizon
    truth = tape.truth.copy()
    actions = tape.action.copy()
    raw, kf, estimate = np.zeros((horizon,len(FEATURES))), np.zeros((horizon,2)), np.zeros((horizon,2))
    source = np.full(horizon, -1, dtype=int)
    arrived_source = np.full(horizon, -1, dtype=int)
    innovation = np.full(horizon, np.nan)
    variance = np.full(horizon, np.nan)
    gain = np.full(horizon, np.nan)
    current_quality = np.zeros(horizon)
    diagnostics = []
    arrival = {}
    capture = {p.source_tick: p for p in tape.packets}
    latest = None
    for tick in range(horizon):
        previous = actions[tick-1] if tick else 0.
        if closed_loop and tick:
            truth[tick] = tape.f[tick] @ truth[tick-1] + tape.b[tick] * previous + tape.process_increments[tick]
        if tick in capture:
            spec = capture[tick]
            value = float(truth[tick,0] + tape.measurement_increments[tick])
            if tick == perturb_source_tick:
                value += perturb_delta
            packet = Packet(spec.source_tick, spec.arrival_tick, value, spec.quality, spec.quality_present)
            arrival.setdefault(packet.arrival_tick, []).append(packet)
        delivered = arrival.pop(tick, ())
        latest_new = max(delivered, key=lambda p: p.source_tick, default=None)
        fresh = latest_new is not None and (latest is None or latest_new.source_tick > latest.source_tick)
        if fresh:
            latest = latest_new
        kf[tick], scores = observer.step(tick, float(previous), delivered)
        if latest_new is not None:
            arrived_source[tick] = latest_new.source_tick
            innovation[tick], variance[tick], gain[tick] = scores[latest_new.source_tick]
            current_quality[tick] = latest_new.quality
            for p in delivered:
                e, s, kg = scores[p.source_tick]
                diagnostics.append(dict(source_tick=p.source_tick, arrival_tick=tick, value=p.value,
                                        quality=p.quality, quality_present=p.quality_present,
                                        innovation=e, innovation_var=s, position_gain=kg))
        if latest is not None:
            source[tick] = latest.source_tick
        age = (tick - latest.source_tick) * cfg.dt if latest is not None else (tick + 1)*cfg.dt
        raw[tick] = [latest.value if latest is not None else 0., latest is not None, fresh,
                     age, cfg.dt, previous, latest.quality if latest is not None else 0.,
                     latest.quality_present if latest is not None else 0.]
        estimate[tick] = kf[tick]
        if residual is not None:
            delta = np.asarray(residual(raw[tick].astype(np.float32), kf[tick].astype(np.float32)), dtype=float)
            if delta.shape != (2,) or not np.all(np.isfinite(delta)):
                raise FloatingPointError("Invalid residual estimate")
            estimate[tick] += delta
        if closed_loop:
            error = tape.reference[tick] - estimate[tick]
            actions[tick] = np.clip(cfg.kp * error[0] + cfg.kd * error[1], -cfg.max_abs_action, cfg.max_abs_action)
    position_error = np.abs(estimate[:,0] - truth[:,0])
    return {"raw": raw.astype(np.float32), "kf": kf.astype(np.float32),
            "truth": truth.astype(np.float32), "estimate": estimate.astype(np.float32),
            "source_tick": source, "arrived_source_tick": arrived_source, "innovation": innovation,
            "innovation_var": variance, "position_gain": gain, "event_records": diagnostics,
            "present": raw[:,1].astype(bool), "fresh": raw[:,2].astype(bool), "quality": current_quality,
            "action": actions, "reference": tape.reference.copy(),
            "state_rmse": np.sqrt(np.mean((estimate - truth)**2, axis=0)).tolist(),
            "post_change_state_rmse": np.sqrt(np.mean((estimate[cfg.change_tick:] - truth[cfg.change_tick:])**2, axis=0)).tolist(),
            "post_change_tracking_rmse": float(np.sqrt(np.mean((truth[cfg.change_tick:,0] - tape.reference[cfg.change_tick:,0])**2))),
            "position_error": position_error, "closed_loop": bool(closed_loop),
            "regime": tape.scenario.regime, "delay": tape.scenario.delay, "seed": tape.scenario.seed,
            "observer_method": method, "deployable_hypothesis_weight_adaptation": method == "adaptive_kf",
            "oracle_parameters_privileged": method == "oracle_kf"}


def calibration_report(cfg):
    """Analytic exact single-acquisition innovation match, not a whole-path match."""
    f, _, q, r = dynamics(cfg)
    _, _, q_up, _ = dynamics(cfg, "q_up")
    _, _, _, r_up = dynamics(cfg, "r_up")
    post = None
    for k in range(cfg.change_tick):
        prior = np.diag([.12**2,.15**2]) if k == 0 else f @ post @ f.T + q
        if k % cfg.acquisition_every == 0:
            g = prior[:,0] / (prior[0,0] + r)
            j = np.eye(2) - np.outer(g,_H)
            post = j @ prior @ j.T + r * np.outer(g,g)
        else:
            post = prior
    p = f @ post @ f.T + q
    pq = f @ post @ f.T + q_up
    sq, sr = float(pq[0,0] + r), float(p[0,0] + r_up)
    if not math.isclose(sq, sr, rel_tol=1e-12):
        raise RuntimeError("Theory calibration did not match innovation variance")
    return {"metric": "first post-change acquisition marginal innovation variance, equally informed capture-time prior",
            "change_tick": cfg.change_tick, "position_innovation_variance_q_up": sq,
            "position_innovation_variance_r_up": sr,
            "measurement_variance_nominal": r, "measurement_variance_r_up": r_up,
            "position_process_variance_nominal": float(q[0,0]), "position_process_variance_q_up": float(q_up[0,0]),
            "oracle_position_gains": {"nominal": float(p[0,0]/(p[0,0]+r)),
                                      "q_up": float(pq[0,0]/sq), "r_up": float(p[0,0]/sr)},
            "explicit_model_switch_regime_separate_from_q": True,
            "scope": "matches one-step marginals at onset only; equal means/variance do not identify source, and later histories may differ"}


def _features_for_attribution(cfg, tape, event_count=16):
    # Fixed nominal observer only; labels are assigned outside this routine.
    result = rollout(cfg, tape)
    events = [r for r in result["event_records"] if r["source_tick"] >= cfg.change_tick]
    if len(events) < event_count:
        raise ValueError("Attribution requires enough post-shift delivered packets")
    z = np.array([e["innovation"]/math.sqrt(e["innovation_var"]) for e in events[:event_count]])
    q = np.array([e["quality"] for e in events[:event_count]])
    features = [float(np.mean(z*z)), float(np.mean(z[1:]*z[:-1])),
                float(np.mean(np.diff(z)**2)), float(np.mean(z)), float(np.mean(np.abs(z)))]
    return ([float(abs(z[0]))], features, [*features,float(q.mean())])


def causal_attribution(cfg, train_seeds, validation_seeds, delay, *, event_count=16, callback=None):
    """Small fixed ridge-logistic development audit of the Q/R distinction."""
    from scipy.optimize import minimize
    from scipy.special import expit
    from scipy.stats import rankdata
    train_seeds, validation_seeds = tuple(int(s) for s in train_seeds), tuple(int(s) for s in validation_seeds)
    if (len(train_seeds) < 4 or len(validation_seeds) < 4 or len(set(train_seeds)) != len(train_seeds)
            or len(set(validation_seeds)) != len(validation_seeds) or set(train_seeds) & set(validation_seeds)
            or event_count < 3):
        raise ValueError("Attribution requires disjoint nontrivial trajectory banks")

    done = 0
    n_trajectories = 2 * (len(train_seeds) + len(validation_seeds))

    def collect(seeds):
        nonlocal done
        x, y = [[], [], []], []
        for seed in seeds:
            for label, regime in enumerate(("q_up", "r_up")):
                row = _features_for_attribution(cfg, generate_tape(cfg, regime, delay, seed, True), event_count)
                for target, part in zip(x,row,strict=True):
                    target.append(part)
                y.append(label)
                done += 1
                if callback is not None:
                    callback(done, n_trajectories)
        return [np.array(v) for v in x], np.array(y)

    train, y = collect(train_seeds)
    validation, yv = collect(validation_seeds)
    scores = {}
    for label, x, xv in zip(("single_innovation_magnitude","causal_history","causal_history_and_quality"),
                           train, validation, strict=True):
        mean, std = x.mean(axis=0), np.maximum(x.std(axis=0), 1e-7)
        z = np.column_stack((np.ones(len(x)), (x - mean)/std))
        zv = np.column_stack((np.ones(len(xv)), (xv - mean)/std))

        def objective(b):
            logits = z @ b
            return float(np.mean(np.logaddexp(0, logits) - y*logits) + .025*(b[1:]@b[1:])), (
                z.T @ (expit(logits)-y)/len(y) + np.r_[0., .05*b[1:]])

        fit = minimize(objective, np.zeros(z.shape[1]), jac=True, method="BFGS")
        if not fit.success:
            raise RuntimeError("Ridge logistic attribution fit did not converge")
        prob = expit(zv @ fit.x)
        rank = rankdata(prob)
        n1, n0 = int(yv.sum()), int(len(yv)-yv.sum())
        scores[label] = {"auc": float((rank[yv==1].sum()-n1*(n1+1)/2)/(n1*n0)),
                         "balanced_accuracy": float(np.mean((prob>=.5)==yv)),
                         "training_trajectories": len(y), "validation_trajectories": len(yv),
                         "post_shift_packets_used": 1 if label == "single_innovation_magnitude" else event_count}
    return {"delay": delay, "scores": scores, "development_only": True,
            "scope": "quality is a noisy simulated proxy, not an observed regime label; paired trajectories, no physical data"}
